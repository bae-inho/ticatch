-- 도메인 설계(docs/domain.md)의 ERD와 불변식을 옮긴 첫 스키마다.
-- 이미 적용된 migration 파일은 고치지 않는다. 바꿀 때는 새 버전 파일을 추가한다.
--
-- 규칙
--   - 시각은 timestamptz로 저장한다(ADR 0005).
--   - 상태 값은 CHECK 제약으로 허용 값을 제한한다. 값을 추가하려면 migration이 필요하다.
--   - PostgreSQL은 외래 키 컬럼에 인덱스를 자동으로 만들지 않는다. 조회에 쓰는 컬럼은 직접 만든다.
--   - 제약 이름 접두어: pk, fk, uk(유일), ck(CHECK), idx(일반 인덱스)

-- 회원 ------------------------------------------------------------------------

CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    name          VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    withdrawn_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'WITHDRAWN')),
    CONSTRAINT ck_users_withdrawn_at CHECK ((status = 'WITHDRAWN') = (withdrawn_at IS NOT NULL))
);

-- 불변식 14: 활성 회원의 이메일은 유일하다. 탈퇴한 회원의 이메일로는 다시 가입할 수 있다.
CREATE UNIQUE INDEX uk_users_active_email ON users (email) WHERE status = 'ACTIVE';

-- 공연 ------------------------------------------------------------------------

CREATE TABLE venue
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(100) NOT NULL,
    address    VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT pk_venue PRIMARY KEY (id)
);

CREATE TABLE concert
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title       VARCHAR(100)  NOT NULL,
    description VARCHAR(2000),
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    updated_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT pk_concert PRIMARY KEY (id),
    CONSTRAINT ck_concert_status CHECK (status IN ('PREPARING', 'OPEN', 'ENDED'))
);

CREATE INDEX idx_concert_status ON concert (status);

CREATE TABLE performance
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    concert_id       BIGINT      NOT NULL,
    venue_id         BIGINT      NOT NULL,
    starts_at        TIMESTAMPTZ NOT NULL,
    booking_opens_at TIMESTAMPTZ NOT NULL,
    status           VARCHAR(20) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_performance PRIMARY KEY (id),
    CONSTRAINT fk_performance_concert FOREIGN KEY (concert_id) REFERENCES concert (id),
    CONSTRAINT fk_performance_venue FOREIGN KEY (venue_id) REFERENCES venue (id),
    CONSTRAINT ck_performance_status CHECK (status IN ('SCHEDULED', 'CANCELED')),
    -- 불변식 12: 예매 오픈은 공연 시작보다 앞선다.
    CONSTRAINT ck_performance_booking_window CHECK (booking_opens_at < starts_at)
);

CREATE INDEX idx_performance_concert ON performance (concert_id);

CREATE TABLE seat_grade
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    performance_id BIGINT      NOT NULL,
    name           VARCHAR(10) NOT NULL,
    price          BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_seat_grade PRIMARY KEY (id),
    CONSTRAINT fk_seat_grade_performance FOREIGN KEY (performance_id) REFERENCES performance (id),
    -- 불변식 11: 회차 안에서 등급 이름은 유일하다.
    CONSTRAINT uk_seat_grade_performance_name UNIQUE (performance_id, name),
    -- 불변식 13: 가격은 0보다 크다.
    CONSTRAINT ck_seat_grade_price CHECK (price > 0)
);

-- 좌석 ------------------------------------------------------------------------

CREATE TABLE seat
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    performance_id BIGINT      NOT NULL,
    seat_grade_id  BIGINT      NOT NULL,
    label          VARCHAR(20) NOT NULL,
    status         VARCHAR(20) NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_seat PRIMARY KEY (id),
    CONSTRAINT fk_seat_performance FOREIGN KEY (performance_id) REFERENCES performance (id),
    CONSTRAINT fk_seat_seat_grade FOREIGN KEY (seat_grade_id) REFERENCES seat_grade (id),
    -- 불변식 11: 회차 안에서 좌석 이름은 유일하다. 회차별 좌석 조회도 이 인덱스를 쓴다.
    CONSTRAINT uk_seat_performance_label UNIQUE (performance_id, label),
    CONSTRAINT ck_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD'))
);

-- 예매 ------------------------------------------------------------------------

CREATE TABLE reservation
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id        BIGINT      NOT NULL,
    performance_id BIGINT      NOT NULL,
    status         VARCHAR(20) NOT NULL,
    total_amount   BIGINT      NOT NULL,
    expires_at     TIMESTAMPTZ NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_reservation PRIMARY KEY (id),
    CONSTRAINT fk_reservation_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_reservation_performance FOREIGN KEY (performance_id) REFERENCES performance (id),
    CONSTRAINT ck_reservation_status CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELED', 'EXPIRED')),
    CONSTRAINT ck_reservation_total_amount CHECK (total_amount > 0)
);

-- 불변식 2: 회원·회차당 결제 대기(PENDING) 예매는 하나다.
CREATE UNIQUE INDEX uk_reservation_pending_user_performance
    ON reservation (user_id, performance_id) WHERE status = 'PENDING';
-- 내 예매 목록
CREATE INDEX idx_reservation_user ON reservation (user_id, id DESC);
-- 회차 취소 때 그 회차의 예매를 찾는다.
CREATE INDEX idx_reservation_performance ON reservation (performance_id);
-- 만료 처리 스케줄러가 시간이 지난 결제 대기 예매만 찾는다.
CREATE INDEX idx_reservation_pending_expires_at ON reservation (expires_at) WHERE status = 'PENDING';

CREATE TABLE reservation_seat
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id BIGINT      NOT NULL,
    seat_id        BIGINT      NOT NULL,
    price          BIGINT      NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_reservation_seat PRIMARY KEY (id),
    CONSTRAINT fk_reservation_seat_reservation FOREIGN KEY (reservation_id) REFERENCES reservation (id),
    CONSTRAINT fk_reservation_seat_seat FOREIGN KEY (seat_id) REFERENCES seat (id),
    CONSTRAINT uk_reservation_seat UNIQUE (reservation_id, seat_id),
    CONSTRAINT ck_reservation_seat_price CHECK (price > 0)
);

-- 결제 ------------------------------------------------------------------------

CREATE TABLE payment
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id  BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    amount          BIGINT      NOT NULL,
    status          VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    paid_at         TIMESTAMPTZ NOT NULL,
    refunded_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL,
    updated_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_payment PRIMARY KEY (id),
    CONSTRAINT fk_payment_reservation FOREIGN KEY (reservation_id) REFERENCES reservation (id),
    CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES users (id),
    -- 불변식 6: 예매당 결제는 하나다.
    CONSTRAINT uk_payment_reservation UNIQUE (reservation_id),
    -- 불변식 7: 같은 결제 요청은 한 번만 처리한다.
    CONSTRAINT uk_payment_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payment_status CHECK (status IN ('PAID', 'REFUNDED')),
    CONSTRAINT ck_payment_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_refunded_at CHECK ((status = 'REFUNDED') = (refunded_at IS NOT NULL))
);

-- 포인트 ----------------------------------------------------------------------

CREATE TABLE point_wallet
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT      NOT NULL,
    balance    BIGINT      NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_wallet PRIMARY KEY (id),
    CONSTRAINT fk_point_wallet_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_point_wallet_user UNIQUE (user_id),
    -- 불변식 4: 잔액은 0 이상이다.
    CONSTRAINT ck_point_wallet_balance CHECK (balance >= 0)
);

CREATE TABLE point_transaction
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    wallet_id       BIGINT      NOT NULL,
    type            VARCHAR(20) NOT NULL,
    amount          BIGINT      NOT NULL,
    balance_after   BIGINT      NOT NULL,
    payment_id      BIGINT,
    idempotency_key VARCHAR(64),
    created_at      TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_point_transaction PRIMARY KEY (id),
    CONSTRAINT fk_point_transaction_wallet FOREIGN KEY (wallet_id) REFERENCES point_wallet (id),
    CONSTRAINT fk_point_transaction_payment FOREIGN KEY (payment_id) REFERENCES payment (id),
    -- 불변식 8: 같은 충전 요청은 한 번만 처리한다.
    CONSTRAINT uk_point_transaction_idempotency_key UNIQUE (idempotency_key),
    -- 불변식 9: 결제당 차감(PAY)·환불(REFUND) 거래는 각각 한 번이다. 충전은 payment_id가 NULL이라 걸리지 않는다.
    CONSTRAINT uk_point_transaction_payment_type UNIQUE (payment_id, type),
    CONSTRAINT ck_point_transaction_type CHECK (type IN ('CHARGE', 'PAY', 'REFUND')),
    CONSTRAINT ck_point_transaction_amount CHECK (amount > 0),
    CONSTRAINT ck_point_transaction_balance_after CHECK (balance_after >= 0),
    -- 충전은 결제와 무관하고 멱등성 키를 가진다. 차감·환불은 결제에 속하고 결제의 멱등성 키를 따른다.
    CONSTRAINT ck_point_transaction_charge_shape CHECK (
        (type = 'CHARGE') = (payment_id IS NULL)
            AND (type = 'CHARGE') = (idempotency_key IS NOT NULL)
        )
);

CREATE INDEX idx_point_transaction_wallet ON point_transaction (wallet_id, id DESC);
